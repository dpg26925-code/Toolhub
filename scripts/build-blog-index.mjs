// Build-time fetch of published blog posts.
// Emits src/generated/blog-posts.ts so the runtime (Cloudflare Workers)
// never has to hit Supabase for blog reads.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../src/generated/blog-posts.ts");

const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const key = process.env.SUPABASE_PUBLISHABLE_KEY || process.env.VITE_SUPABASE_PUBLISHABLE_KEY;

function emit(posts) {
  mkdirSync(dirname(OUT), { recursive: true });
  const body =
    `// AUTO-GENERATED by scripts/build-blog-index.mjs — do not edit by hand.\n` +
    `// Regenerated on every build via the \`prebuild\` npm script.\n` +
    `import type { StaticBlogPost } from "./blog-index";\n\n` +
    `export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};\n` +
    `export const STATIC_BLOG_POSTS: StaticBlogPost[] = ${JSON.stringify(posts, null, 2)};\n`;
  writeFileSync(OUT, body);
  console.log(`[build-blog] wrote ${posts.length} posts -> ${OUT}`);
}

if (!url || !key) {
  console.warn("[build-blog] Supabase env vars missing — writing empty index");
  emit([]);
  process.exit(0);
}

const select = "slug,title,excerpt,content,cover_image,meta_title,meta_description,published_at,created_at,updated_at";
const endpoint = `${url}/rest/v1/blog_posts?select=${encodeURIComponent(select)}&published=eq.true&order=published_at.desc.nullslast`;

try {
  const res = await fetch(endpoint, { headers: { apikey: key, Accept: "application/json" } });
  if (!res.ok) {
    console.warn(`[build-blog] Supabase ${res.status} — writing empty index`);
    emit([]);
    process.exit(0);
  }
  const posts = await res.json();
  emit(Array.isArray(posts) ? posts : []);
} catch (err) {
  console.warn("[build-blog] fetch failed — writing empty index:", err?.message || err);
  emit([]);
}
